#include <iostream>
using namespace std;

int main() {
    int n,i,j;
    cin >> n;

    for(i = 0; i < n+n+1;i++){
        for(j = 0; j < n + n + 1;j++){
            if(i % 2 == 1 && (i*10)+j == 1+(2*j))
                cout << " ";
            else
                cout << "* ";
        }
        cout << "\n";
    }

    return 0;
}
